import { contextBridge, ipcRenderer } from 'electron';
import type { DesktopApi } from '../shared/types/desktop-api';
const desktopApi: DesktopApi = {
  platform: process.platform,
  openDashboard: () => ipcRenderer.invoke('dashboard:open'),
  listNotes: () => ipcRenderer.invoke('notes:list'),
  getNote: (id) => ipcRenderer.invoke('notes:get', id),
  createNote: () => ipcRenderer.invoke('notes:create'),
  saveNote: (id, change) => ipcRenderer.invoke('notes:save', id, change),
  deleteNote: (id) => ipcRenderer.invoke('notes:delete', id),
  openNote: (id) => ipcRenderer.invoke('notes:open', id),
  getFocus: () => ipcRenderer.invoke('focus:get'),
  startFocus: (kind, minutes) => ipcRenderer.invoke('focus:start', kind, minutes),
  pauseFocus: () => ipcRenderer.invoke('focus:pause'),
  resumeFocus: () => ipcRenderer.invoke('focus:resume'),
  stopFocus: () => ipcRenderer.invoke('focus:stop'),
  setFocusSound: (enabled) => ipcRenderer.invoke('focus:sound', enabled),
  getAppearance: () => ipcRenderer.invoke('appearance:get'),
  setAppearance: (change) => ipcRenderer.invoke('appearance:set', change),
  craftItem: (recipeId) => ipcRenderer.invoke('crafting:craft', recipeId),
  listTools: () => ipcRenderer.invoke('tools:list'),
  setToolEnabled: (id, enabled) => ipcRenderer.invoke('tools:set-enabled', id, enabled),
  getSedentary: () => ipcRenderer.invoke('sedentary:get'),
  configureSedentary: (settings) => ipcRenderer.invoke('sedentary:configure', settings),
  snoozeSedentary: (minutes) => ipcRenderer.invoke('sedentary:snooze', minutes),
  resetSedentary: () => ipcRenderer.invoke('sedentary:reset'),
  getDailySummary: () => ipcRenderer.invoke('summary:get'),
  getAppSettings: () => ipcRenderer.invoke('settings:get'),
  updateAppPreference: (change) => ipcRenderer.invoke('settings:update', change),
  setInputTracking: (enabled) => ipcRenderer.invoke('settings:set-input', enabled),
  resetAllData: () => ipcRenderer.invoke('settings:reset-all'),
  getStatistics: () => ipcRenderer.invoke('statistics:get'),
  clearStatistics: () => ipcRenderer.invoke('statistics:clear'),
  exportStatistics: () => ipcRenderer.invoke('statistics:export'),
};
contextBridge.exposeInMainWorld('desktopApi', desktopApi);
