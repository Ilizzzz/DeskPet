import type { Note, NoteChange } from './note';
import type { FocusSnapshot } from './focus';
import type { Appearance, AppearanceChange } from './appearance';
import type { StatisticsSnapshot } from './statistics';
import type { ToolId, ToolState } from './tool';
import type { SedentarySettings, SedentarySnapshot } from './sedentary';
import type { DailySummary } from './summary';
export interface DesktopApi {
  readonly platform: NodeJS.Platform;
  openDashboard(): Promise<void>;
  listNotes(): Promise<Note[]>;
  getNote(id: number): Promise<Note>;
  createNote(): Promise<Note[]>;
  saveNote(id: number, change: NoteChange): Promise<Note[]>;
  deleteNote(id: number): Promise<Note[]>;
  openNote(id: number): Promise<void>;
  getFocus(): Promise<FocusSnapshot>;
  startFocus(kind: 'focus' | 'break', minutes: number): Promise<FocusSnapshot>;
  pauseFocus(): Promise<FocusSnapshot>;
  resumeFocus(): Promise<FocusSnapshot>;
  stopFocus(): Promise<FocusSnapshot>;
  setFocusSound(enabled: boolean): Promise<FocusSnapshot>;
  getAppearance(): Promise<Appearance>;
  setAppearance(change: AppearanceChange): Promise<Appearance>;
  craftItem(recipeId: string): Promise<Appearance>;
  listTools(): Promise<ToolState[]>;
  setToolEnabled(id: ToolId, enabled: boolean): Promise<ToolState[]>;
  getSedentary(): Promise<SedentarySnapshot>;
  configureSedentary(settings: SedentarySettings): Promise<SedentarySnapshot>;
  snoozeSedentary(minutes: number): Promise<SedentarySnapshot>;
  resetSedentary(): Promise<SedentarySnapshot>;
  getDailySummary(): Promise<DailySummary>;
  getStatistics(): Promise<StatisticsSnapshot>;
  clearStatistics(): Promise<boolean>;
  exportStatistics(): Promise<boolean>;
}
